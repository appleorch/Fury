// Regenerates src/lib/sampleRouteData.ts from an OSRM route (demo drive used by Simulation mode and
// the optional sample history). Usage: node scripts/build-sample-route.mjs <osrm-route.json>
import { readFileSync, writeFileSync } from 'node:fs';

const file = process.argv[2];
if (!file) throw new Error('usage: build-sample-route.mjs <osrm-route.json>');
const data = JSON.parse(readFileSync(file, 'utf8'));
const route = data.routes[0];
const leg = route.legs[0];
const speeds = leg.annotation.speed.map((s) => Math.round(s * 10) / 10);
// Intersections where the car may stop: every turn / merge onto a surface street.
const stops = leg.steps
  .filter((s) => ['turn', 'end of road', 'arrive'].includes(s.maneuver.type) || (s.maneuver.type === 'merge' && /Expressway/.test(s.name)))
  .map((s) => [Math.round(s.maneuver.location[1] * 1e6) / 1e6, Math.round(s.maneuver.location[0] * 1e6) / 1e6]);

const out = `// Generated by scripts/build-sample-route.mjs from an OSRM route. Road data © OpenStreetMap contributors.
// A ~13 km commute from Willow Glen, San Jose to Cupertino: residential streets, an arterial, I-280 and an expressway.
export const SAMPLE_POLYLINE = ${JSON.stringify(route.geometry)};
/** Free-flow speed (m/s) for each geometry segment. */
export const SAMPLE_SPEEDS: number[] = ${JSON.stringify(speeds)};
/** Intersections where the simulated driver may stop, [lat, lon]. */
export const SAMPLE_STOPS: [number, number][] = ${JSON.stringify(stops)};
`;
writeFileSync(new URL('../src/lib/sampleRouteData.ts', import.meta.url), out);
console.log('wrote', speeds.length, 'segments,', stops.length, 'stops');
